#!/usr/bin/env node
// Generates, from the actual route definitions in server/src/modules:
//   docs/api/endpoints.md  - REST reference (method, path, permission, notes)
//   docs/api/inventory.md  - inventory: purpose, auth, frontend consumers, tests that exercise it
// Usage: node scripts/gen-api-docs.mjs [--check]   (--check: exit 1 if an endpoint has no purpose)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PURPOSES } from './api-purposes.mjs';

const root = fileURLToPath(new URL('..', import.meta.url)); // works on Windows (no "/D:/..." paths)
const read = (p) => readFileSync(join(root, p), 'utf8');
const walk = (dir) => readdirSync(join(root, dir)).flatMap((n) => {
  const rel = `${dir}/${n}`;
  return statSync(join(root, rel)).isDirectory() ? walk(rel) : [rel];
});

const app = read('server/src/app.ts');
const mounts = {};
for (const m of app.matchAll(/api\.use\('([^']+)'(?:,\s*csrfProtect)?,\s*(\w+Router)\)/g)) mounts[m[2]] = '/api' + m[1];

const clientFiles = walk('client/src').filter((f) => /\.(ts|tsx)$/.test(f) && !/\.test\./.test(f)).map((f) => [f, read(f)]);
const testFiles = [...walk('server/tests'), ...walk('tests/e2e'), ...walk('client/src')]
  .filter((f) => /\.(test|spec)\.(ts|tsx)$/.test(f)).map((f) => [f, read(f)]);

/** Regex finding a call of this path in source: ":param" may be a literal or a ${...} template. */
function pathRegex(path) {
  const parts = path.split(/(:\w+)/).map((p) => (p.startsWith(':') ? '(?:\\$\\{[^}]+\\}|[A-Za-z0-9_-]+)' : p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
  return new RegExp(`['"\`]${parts.join('')}(?=['"\`?$])`);
}
/** Same, but the dynamic segment may be any template (e.g. reports/${type}). */
function looseRegex(path) {
  return new RegExp(`['"\`]${path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/:\w+/g, '(?:\\$\\{[^}]+\\}|[A-Za-z0-9_-]+)')}`);
}

const rows = []; const missing = [];
for (const f of readdirSync(join(root, 'server/src/modules')).filter((x) => x.endsWith('.ts')).sort()) {
  const src = read(`server/src/modules/${f}`);
  const gated = {};
  for (const m of src.matchAll(/(\w+Router)\.use\(requireFeature\('([^']+)'\)\)/g)) gated[m[1]] = m[2];
  for (const m of src.matchAll(/(\w+Router)\.(get|post|patch|put|delete|all)\('([^']+)',([^\n]*)/g)) {
    const [, router, method, p, rest] = m;
    const perms = [...rest.matchAll(/can(Any)?\(([^)]*)\)/g)].map((x) => (x[1] ? 'any of ' : '') + x[2].replace(/'/g, '')).join('; ');
    const notes = [rest.includes('idempotent(true)') ? 'Idempotency-Key required' : rest.includes('idempotent(') ? 'Idempotency-Key optional' : '', gated[router] ? `Standard package (${gated[router]})` : ''].filter(Boolean).join('; ');
    const base = mounts[router] ?? '?';
    const path = `${base}${p === '/' ? '' : p}`;
    const pub = ['publicRouter', 'publicSiteRouter', 'healthRouter', 'smsWebhookRouter'].includes(router) || (router === 'authRouter' && /login|logout|reset/.test(p));
    const auth = perms || (router === 'authRouter' && p === '/me' ? 'session' : pub ? (router === 'smsWebhookRouter' ? 'provider signature / token' : 'public') : 'authenticated');
    const key = `${method.toUpperCase()} ${path}`;
    if (!PURPOSES[key]) missing.push(key);
    const rx = pathRegex(path); const lx = looseRegex(path);
    const consumers = clientFiles.filter(([, s]) => rx.test(s) || lx.test(s)).map(([n]) => relative('client/src', n).replace(/\\/g, '/'));
    const tests = testFiles.filter(([, s]) => rx.test(s) || lx.test(s)).map(([n]) => n.replace(/\\/g, '/').replace(/^.*\//, ''));
    rows.push({ method: method.toUpperCase(), path, auth, notes, source: f, purpose: PURPOSES[key] ?? '', consumers, tests });
  }
}

const conventions = `**Conventions**
- Base path \`/api\`. JSON in, JSON out: \`{ ok: true, data, meta? }\` or \`{ ok: false, error: { code, message, details? } }\`.
- Authentication: httpOnly session cookie \`sms_sid\` set by \`POST /api/auth/login\`.
- CSRF: every non-GET request from a signed-in user must send header \`X-CSRF-Token\` equal to the \`sms_csrf\` cookie.
- Permissions are evaluated on the server from the user's role in the database (never from the client).
- Paginated lists accept \`page\`, \`pageSize\` (≤200), \`q\`, \`sort\` and return \`meta.total\`.
- Errors: 400 validation, 401 not signed in, 403 forbidden / CSRF / PACKAGE, 404, 409 conflict/duplicate, 422 attendance window rules, 429 rate limit.
- Report endpoints accept \`format=json|csv|xlsx|pdf\`.`;

writeFileSync(join(root, 'docs/api/endpoints.md'), `# REST API reference

_Generated by \`node scripts/gen-api-docs.mjs\` from \`server/src/modules\`. Do not edit by hand._

${conventions}

| Method | Path | Permission | Notes | Source |
|---|---|---|---|---|
${rows.map((r) => `| ${r.method} | \`${r.path}\` | ${r.auth} | ${r.notes} | ${r.source} |`).join('\n')}

Total endpoints: ${rows.length}
`);

const untested = rows.filter((r) => !r.tests.length);
const unused = rows.filter((r) => !r.consumers.length);
writeFileSync(join(root, 'docs/api/inventory.md'), `# API inventory

_Generated by \`node scripts/gen-api-docs.mjs\` from the route definitions, the client source and the test
suites. Do not edit by hand; purposes live in \`scripts/api-purposes.mjs\`._

- **Frontend consumer**: client files that call the endpoint. "—" means no screen calls it (see notes below).
- **Verified by**: test files that exercise it (server integration tests run against a real in-memory
  MongoDB replica set; \`app.spec.ts\` is the browser end-to-end suite).

${conventions}

| Method | Path | Purpose | Auth / permission | Frontend consumer | Verified by |
|---|---|---|---|---|---|
${rows.map((r) => `| ${r.method} | \`${r.path}\` | ${r.purpose} | ${r.auth}${r.notes ? `; ${r.notes}` : ''} | ${r.consumers.join(', ') || '—'} | ${r.tests.join(', ') || '**not covered**'} |`).join('\n')}

**Totals**: ${rows.length} endpoints · ${rows.length - untested.length} covered by automated tests · ${rows.length - unused.length} called by the web app.

**Endpoints without a screen (by design)**
${unused.map((r) => `- \`${r.method} ${r.path}\` — ${r.purpose}`).join('\n') || '- none'}
`);

console.log(`endpoints: ${rows.length}, tested: ${rows.length - untested.length}, used by client: ${rows.length - unused.length}`);
if (untested.length) console.log('UNTESTED:\n' + untested.map((r) => `  ${r.method} ${r.path}`).join('\n'));
if (unused.length) console.log('NO CLIENT CONSUMER:\n' + unused.map((r) => `  ${r.method} ${r.path}`).join('\n'));
if (missing.length) { console.error('MISSING PURPOSE:\n' + missing.map((k) => `  ${k}`).join('\n')); if (process.argv.includes('--check')) process.exit(1); }
