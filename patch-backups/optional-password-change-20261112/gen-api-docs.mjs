#!/usr/bin/env node
// Generates docs/api/endpoints.md from the actual route definitions in server/src/modules.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const app = readFileSync(join(root, 'server/src/app.ts'), 'utf8');
const mounts = {};
for (const m of app.matchAll(/api\.use\('([^']+)'(?:,\s*csrfProtect)?,\s*(\w+Router)\)/g)) mounts[m[2]] = '/api' + m[1];

const rows = [];
const dir = join(root, 'server/src/modules');
for (const f of readdirSync(dir).filter((x) => x.endsWith('.ts')).sort()) {
  const src = readFileSync(join(dir, f), 'utf8');
  const gated = {};
  for (const m of src.matchAll(/(\w+Router)\.use\(requireFeature\('([^']+)'\)\)/g)) gated[m[1]] = m[2];
  for (const m of src.matchAll(/(\w+Router)\.(get|post|patch|put|delete|all)\('([^']+)',([^\n]*)/g)) {
    const [, router, method, path, rest] = m;
    const perms = [...rest.matchAll(/can(Any)?\(([^)]*)\)/g)].map((x) => (x[1] ? 'any of ' : '') + x[2].replace(/'/g, '')).join('; ');
    const extras = [rest.includes('idempotent(true)') ? 'Idempotency-Key required' : rest.includes('idempotent(') ? 'Idempotency-Key optional' : '', gated[router] ? `Standard package (${gated[router]})` : ''].filter(Boolean).join('; ');
    const base = mounts[router] ?? '?';
    const pub = ['publicRouter', 'healthRouter', 'smsWebhookRouter'].includes(router) || (router === 'authRouter' && /login|logout|reset|me/.test(path));
    rows.push(`| ${method.toUpperCase()} | \`${base}${path === '/' ? '' : path}\` | ${pub && !perms ? (router === 'authRouter' && path === '/me' ? 'session' : 'public') : perms || 'authenticated'} | ${extras} | ${f} |`);
  }
}
const out = `# REST API reference

_Generated by \`node scripts/gen-api-docs.mjs\` from \`server/src/modules\`. Do not edit by hand._

**Conventions**
- Base path \`/api\`. JSON in, JSON out: \`{ ok: true, data, meta? }\` or \`{ ok: false, error: { code, message, details? } }\`.
- Authentication: httpOnly session cookie \`sms_sid\` set by \`POST /api/auth/login\`.
- CSRF: every non-GET request from a signed-in user must send header \`X-CSRF-Token\` equal to the \`sms_csrf\` cookie.
- Permissions are evaluated on the server from the user's role in the database (never from the client).
- Paginated lists accept \`page\`, \`pageSize\` (≤200), \`q\`, \`sort\` and return \`meta.total\`.
- Errors: 400 validation, 401 not signed in, 403 forbidden / CSRF / PACKAGE / PASSWORD_CHANGE_REQUIRED, 404, 409 conflict/duplicate, 422 attendance window rules, 429 rate limit.
- Report endpoints accept \`format=json|csv|xlsx|pdf\`.

| Method | Path | Permission | Notes | Source |
|---|---|---|---|---|
${rows.join('\n')}

Total endpoints: ${rows.length}
`;
writeFileSync(join(root, 'docs/api/endpoints.md'), out);
console.log(`docs/api/endpoints.md: ${rows.length} endpoints`);
